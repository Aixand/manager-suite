#!/usr/bin/env python3
"""Package-local development commands; source release operations belong to the suite.

Adapted to the installation-template revision-2 command contract. The canonical
copy lives in scripts/development/python_dev.py; package copies are self-contained.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib

LOCAL = ("help", "doctor", "develop", "lock", "check", "test", "build")
RELEASE = (
    "package",
    "verify",
    "install",
    "reinstall",
    "upgrade",
    "uninstall",
    "inspect",
    "commands",
    "plan",
    "rollback",
    "prune",
    "export-release",
)


def run(command, root, *, capture=False):
    environment = dict(os.environ)
    for name in ("PYTHONPATH", "PYTHONHOME", "VIRTUAL_ENV"):
        environment.pop(name, None)
    print("+ " + " ".join(map(str, command)), file=sys.stderr, flush=True)
    result = subprocess.run(
        list(map(str, command)),
        cwd=root,
        env=environment,
        text=True,
        stdout=subprocess.PIPE if capture else None,
        check=True,
    )
    return result.stdout


def requirement_blocks(text):
    blocks = []
    for line in text.splitlines(keepends=True):
        if line.strip() and not line.startswith((" ", "\t", "#")):
            blocks.append(line)
        elif blocks:
            blocks[-1] += line
    return blocks


def sources(root, config):
    result = {}
    for name, relative in config.get("sources", {}).items():
        path = (root / relative).resolve()
        if not (path / "pyproject.toml").is_file():
            raise ValueError(
                f"Missing local dependency {name}: {path}. Use --wheelhouse without --local for a standalone checkout."
            )
        data = tomllib.loads((path / "pyproject.toml").read_text())["project"]
        if data["name"] != name:
            raise ValueError(f"Local source identity differs: {name}: {path}")
        result[name] = (path, data["version"])
    return result


def compile_lock(root, config, args, uv):
    project = tomllib.loads((root / "pyproject.toml").read_text())["project"]
    extra = ",".join(config["development"].get("extras", []))
    inputs = [
        "-c " + str(root / "development-constraints.txt"),
        "-e ." + (f"[{extra}]" if extra else ""),
    ]
    local_sources = sources(root, config) if args.local else {}
    inputs += ["-e " + str(path) for path, _ in local_sources.values()]
    inputs += config["development"]["tools"]
    with tempfile.TemporaryDirectory(prefix="package-lock-") as temporary:
        temporary = Path(temporary)
        input_file, output_file = (
            temporary / "requirements.in",
            temporary / "requirements.lock",
        )
        input_file.write_text("\n".join(inputs) + "\n")
        command = [
            uv,
            "pip",
            "compile",
            input_file,
            "--no-sources",
            "--universal",
            "--python-version",
            "3.11",
            "--generate-hashes",
            "--no-header",
            "--no-annotate",
            "--no-emit-package",
            project["name"],
            "-o",
            output_file,
        ]
        if args.wheelhouse:
            command += ["--find-links", args.wheelhouse.resolve()]
        run(command, root, capture=True)
        blocks = requirement_blocks(output_file.read_text())
        bypath = {
            path: (name, version) for name, (path, version) in local_sources.items()
        }
        normalized = []
        for block in blocks:
            if block.startswith("-e "):
                path = Path(block.splitlines()[0][3:].strip()).resolve()
                name, version = bypath[path]
                normalized.append(f"{name}=={version}\n")
            else:
                normalized.append(block)
        (root / "requirements-dev.lock").write_text(
            "# Generated by ./dev.sh lock; edit development.toml and regenerate.\n"
            "# First-party packages can come from wheels or explicit --local sources.\n"
            + "".join(normalized)
        )


def develop(root, config, args, uv, python):
    lock = root / "requirements-dev.lock"
    if not lock.is_file():
        raise ValueError("Missing requirements-dev.lock. Run ./dev.sh lock first.")
    if not python.is_file():
        request = (
            args.python
            or os.environ.get("UV_PYTHON")
            or (root / ".python-version").read_text().strip()
        )
        run([uv, "venv", root / ".venv", "--python", request], root)
    text = lock.read_text()
    if args.local:
        local_sources = sources(root, config)
        blocks = []
        for block in requirement_blocks(text):
            name = re.split(r"[=<>!~;\s\[]", block, maxsplit=1)[0]
            if name in local_sources:
                blocks.append("-e " + str(local_sources[name][0]) + "\n")
            else:
                blocks.append(block)
        text = "".join(blocks)
    with tempfile.TemporaryDirectory(prefix="package-develop-") as temporary:
        selected = Path(temporary) / "requirements.lock"
        selected.write_text(text)
        command = [uv, "pip", "sync", "--python", python, "--no-sources", selected]
        if args.wheelhouse:
            command += ["--find-links", args.wheelhouse.resolve()]
        run(command, root)
    extras = ",".join(config["development"].get("extras", []))
    selected = "." + (f"[{extras}]" if extras else "")
    run(
        [
            uv,
            "pip",
            "install",
            "--python",
            python,
            "--no-deps",
            "--no-sources",
            "--no-build-isolation",
            "--editable",
            selected,
        ],
        root,
    )
    run([uv, "pip", "check", "--python", python], root)


def build(root, args, uv, python):
    output = (args.output or root / "dist").resolve()
    output.mkdir(parents=True, exist_ok=True)

    # setuptools may retain removed modules in build/lib. Always use fresh sources.
    def ignored(directory, names):
        skip = {
            "build",
            "dist",
            "venv",
            "__pycache__",
            "AGENTS.md",
            ".git",
            ".hg",
            ".svn",
            ".venv",
            ".venv-hooks",
            ".ruff_cache",
            ".pytest_cache",
            ".mypy_cache",
            ".tox",
            ".nox",
        }
        return [
            name
            for name in names
            if name in skip
            or name.endswith(".egg-info")
            or (name.startswith(".env") and name != ".env.example")
            or name.endswith((".pyc", ".pyo"))
            or (Path(directory) / name).resolve() == output
        ]

    with tempfile.TemporaryDirectory(prefix="package-build-") as temporary:
        snapshot = Path(temporary) / "source"
        shutil.copytree(root, snapshot, ignore=ignored)
        request = (
            args.python
            or os.environ.get("UV_PYTHON")
            or (
                str(python)
                if python.is_file()
                else (root / ".python-version").read_text().strip()
            )
        )
        run(
            [
                uv,
                "build",
                "--no-sources",
                "--python",
                request,
                "--out-dir",
                output,
                snapshot,
            ],
            root,
        )


def release(root, operation, arguments):
    config = tomllib.loads((root / "development.toml").read_text())["release"]
    suite = (root / config["suite"]).resolve()
    runner = suite / "scripts/manager_dev.py"
    if not runner.is_file():
        raise ValueError(
            "Managed release operations require the full manager-suites checkout. Use build for standalone wheel/source artifacts."
        )
    if "component" in config:
        if operation not in ("package", "verify", "export-release"):
            raise ValueError(
                "Libraries install into a consumer environment through pip/uv; they have no global command lifecycle."
            )
        command = [sys.executable, "-B", runner, operation, *arguments]
        if operation == "package":
            command += ["--component", config["component"]]
    else:
        command = [
            sys.executable,
            "-B",
            runner,
            "--child",
            config["product"],
            operation,
            *arguments,
        ]
    run(command, root)


def main():
    root = Path(__file__).resolve().parent
    arguments = sys.argv[1:]
    try:
        if arguments and arguments[0] in RELEASE:
            release(root, arguments[0], arguments[1:])
            return 0
        parser = argparse.ArgumentParser(description=__doc__)
        parser.add_argument("command", nargs="?", default="help", choices=LOCAL)
        parser.add_argument(
            "--local",
            action="store_true",
            help="Explicitly use the source dependencies in development.toml (develop/lock)",
        )
        parser.add_argument(
            "--wheelhouse", type=Path, help="Dependency wheel directory (develop/lock)"
        )
        parser.add_argument(
            "--python",
            help="Interpreter for creating the local environment or building artifacts",
        )
        parser.add_argument(
            "--output", type=Path, help="Build output directory (default: dist/)"
        )
        parser.add_argument(
            "--release",
            action="store_true",
            help="Build with the Python backend; no separate optimization profile",
        )
        args = parser.parse_args(arguments)
        if args.command == "help":
            parser.print_help()
            print("\nManaged suite release operations: " + " ".join(RELEASE))
            print(
                "They require the full manager-suites checkout; libraries have no global installation."
            )
            return 0
        if (args.local or args.wheelhouse) and args.command not in ("develop", "lock"):
            parser.error("--local and --wheelhouse apply only to develop/lock")
        if (args.output or args.release) and args.command != "build":
            parser.error("--output and --release apply only to build")
        if args.python and args.command not in ("develop", "build"):
            parser.error("--python applies only to develop/build")
        config = tomllib.loads((root / "development.toml").read_text())
        uv = shutil.which("uv")
        if not uv:
            raise ValueError(
                "Install uv first; the supported development version is 0.12.7."
            )
        python = (
            root / ".venv" / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
        )
        if args.command == "doctor":
            run([uv, "--version"], root)
            print(
                f"Checkout: {root}\nEnvironment: {python}\nEnvironment created: {python.is_file()}\nDevelopment lock: {(root / 'requirements-dev.lock').is_file()}"
            )
        elif args.command == "lock":
            compile_lock(root, config, args, uv)
        elif args.command == "develop":
            develop(root, config, args, uv, python)
        elif args.command == "build":
            build(root, args, uv, python)
        else:
            if not python.is_file():
                raise ValueError(
                    "Run ./dev.sh develop first (add --local inside the suite checkout)."
                )
            if args.command == "check":
                run([uv, "pip", "check", "--python", python], root)
                run(
                    [python, "-m", "ruff", "check", "--select", "E9,F63,F7,F82", "."],
                    root,
                )
            else:
                run([python, "-m", "unittest", "discover", "-s", "tests", "-v"], root)
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError, KeyError) as error:
        print(str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
